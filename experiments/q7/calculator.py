"""Basic arithmetic operations required by the supplied calculator tests."""


class Calculator:
    """Provide addition, subtraction, multiplication, and division."""

    def add(self, a, b):
        return a + b

    def subtract(self, a, b):
        return a - b

    def multiply(self, a, b):
        return a * b

    def divide(self, a, b):
        if b == 0:
            raise ValueError("Cannot divide by zero")
        return a / b
